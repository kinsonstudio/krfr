# ---------- 生成 strings.xml ----------
def xml_escape(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
             .replace("'", "\\'"))

def build_xml(mapping):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>",
             '    <string name="app_name">krfr</string>']
    for key in sorted(mapping):
        val = mapping[key]
        lines.append('    <string name="%s">%s</string>' % (key, xml_escape(val)))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"

